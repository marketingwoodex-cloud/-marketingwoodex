/*
 * tools/build-demo-copy.mjs — regenerate woodex-live-p23/demo-preview/ from woodex-live-p23/admin/.
 *
 *   node tools/build-demo-copy.mjs            # rebuild the copy
 *   node tools/build-demo-copy.mjs --check    # only report drift, write nothing
 *
 * The copy is the Woodex admin that runs with no PHP: the same files, plus demo-api.js (hand-written,
 * never overwritten by this script), demo-data.js (generated from tools/demo-data.mjs) and
 * demo-help.html. The copied index.html differs in exactly two ways: its <base href> points at the
 * copy instead of /admin/, and two <script> tags (demo-data.js, demo-api.js) sit just before admin.js
 * so they are in place before the app runs. Nothing under admin/ is ever written to.
 *
 * Exit 0 = the copy on disk is what these sources produce.
 */
import { cp, mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "woodex-live-p23", "admin");
const OUT = join(ROOT, "woodex-live-p23", "demo-preview");
const FIXTURES = join(ROOT, "tools", "demo-data.mjs");
const HAND_WRITTEN = new Set(["demo-api.js"]); /* authored by hand, never regenerated */
const CHECK = process.argv.includes("--check");

/* ---- 1. the fixture module becomes a plain browser script ------------------------------------- */
function toBrowserScript(esm) {
  const body = esm
    .replace(/^export const /gm, "const ")
    .replace(/^export function /gm, "function ")
    .replace(/^export \{[^}]*\};\s*$/m, "");
  const names = ["DEMO", "respond", "KNOWN_ACTIONS", "CATEGORIES", "PAY", "NODES", "EXPENSES", "QUOTES",
    "INVOICES", "LEADS", "CLIENTS", "MILESTONES", "PAGES", "MEDIA", "ACTIONS", "COMPANY", "round2"];
  return [
    "/* generated by tools/build-demo-copy.mjs from tools/demo-data.mjs — do not edit here.",
    "   The demo server (tools/demo-server.mjs) imports the same fixtures as an ES module, so the two",
    "   demos cannot drift apart: this is a plain browser script only because the admin loads classic",
    "   scripts. */",
    "(function () {",
    '"use strict";',
    body.trim(),
    "",
    "window.WX_DEMO_DATA = { " + names.join(", ") + " };",
    "})();",
    "",
  ].join("\n");
}

