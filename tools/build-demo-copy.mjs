/* ---- 3. the two edits the copy's index.html gets ------------------------------------------------
   admin/index.html carries <base href="/admin/">, so every relative URL on the page (its stylesheets,
   its 60 module scripts, the hash links in the sidebar) resolves against /admin/. In the copy that
   base points at the copy itself — otherwise the copy would keep loading the original's files and its
   own extra scripts would 404 — and the two demo scripts are added right before admin.js. */
const BASE_FROM = '<base href="/admin/">';
const BASE_TO = '<base href="/demo-preview/">';
const TAGS = '<script src="demo-data.js" defer></script>\n<script src="demo-api.js" defer></script>\n';
function patchIndex(html) {
  let out = html;
  if (out.includes(BASE_FROM)) out = out.replace(BASE_FROM, BASE_TO);
  else if (!out.includes(BASE_TO)) throw new Error("index.html: the <base> tag was not found");
  if (out.includes('src="demo-api.js"')) return out;
  const anchor = '<script src="admin.js" defer></script>';
  if (!out.includes(anchor)) throw new Error("index.html: could not find the admin.js script tag");
  return out.replace(anchor, TAGS + anchor);
}

async function walk(dir, base = dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, e.name);
    if (e.isDirectory()) out.push(...await walk(full, base));
    else out.push(relative(base, full));
  }
  return out;
}

const same = async (p, text) => {
  try { return (await readFile(p, "utf8")) === text; } catch { return false; }
};

async function main() {
  const fixtureSrc = await readFile(FIXTURES, "utf8");
  const planned = [
    ["demo-data.js", toBrowserScript(fixtureSrc)],
    ["demo-help.html", helpPage()],
    ["README.md", readme()],
  ];
  const adminFiles = await walk(SRC);
  const indexHtml = patchIndex(await readFile(join(SRC, "index.html"), "utf8"));

  if (CHECK) {
    const drift = [];
    for (const [name, text] of planned) if (!(await same(join(OUT, name), text))) drift.push(name);
    for (const rel of adminFiles) {
      const b = join(OUT, rel);
      const sa = await stat(join(SRC, rel)).catch(() => null);
      const sb = await stat(b).catch(() => null);
      if (!sb) { drift.push(rel + " (missing)"); continue; }
      if (rel === "index.html") { if (!(await same(b, indexHtml))) drift.push("index.html"); continue; }
      if (!sa || sa.size !== sb.size) drift.push(rel + " (different size)");
    }
    console.log(drift.length
      ? "  demo-preview is out of date:\n    " + drift.join("\n    ")
      : "  demo-preview matches admin/ + tools/demo-data.mjs (" + adminFiles.length + " files, 0 drift)");
    process.exit(drift.length ? 1 : 0);
  }

  await mkdir(OUT, { recursive: true });
  for (const rel of adminFiles) {
    if (HAND_WRITTEN.has(rel)) continue;
    await mkdir(dirname(join(OUT, rel)), { recursive: true });
    await cp(join(SRC, rel), join(OUT, rel), { force: true });
  }
  await writeFile(join(OUT, "index.html"), indexHtml);
  for (const [name, text] of planned) await writeFile(join(OUT, name), text);
  console.log("  copied " + adminFiles.length + " admin files → woodex-live-p23/demo-preview/");
  console.log("  wrote demo-data.js · demo-help.html · README.md · index.html (+2 script tags)");
  console.log("  admin/ untouched; demo-api.js left as written by hand");
}

await main();
