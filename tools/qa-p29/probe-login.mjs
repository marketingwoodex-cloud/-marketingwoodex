import pptr from 'puppeteer-core';
import cm from '@sparticuz/chromium';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const ROOT=path.resolve('node_modules');
const { inflate } = await import(pathToFileURL(path.join(ROOT,'@sparticuz/chromium/build/lambdafs.js')).href);
const libDir=await inflate(path.join(ROOT,'@sparticuz/chromium/bin/al2023.tar.br'));
process.env.LD_LIBRARY_PATH=[path.join(libDir,'lib'),process.env.LD_LIBRARY_PATH||''].filter(Boolean).join(':');
const b=await pptr.launch({executablePath:await cm.executablePath(),args:cm.args,headless:true,defaultViewport:{width:1280,height:900}});
const p=await b.newPage();
p.on('pageerror',e=>console.log('PAGEERROR:', String(e.message).slice(0,180)));
p.on('console',m=>{ if(m.type()==='error') console.log('CONSOLE:', m.text().slice(0,180)); });
p.on('requestfailed',r=>console.log('REQFAIL:', r.url().slice(-60), r.failure()?.errorText));
p.on('response',r=>{ if(r.status()>=400) console.log('HTTP', r.status(), r.url().slice(-70)); });
await p.goto('http://127.0.0.1:8080/admin/',{waitUntil:'networkidle2',timeout:30000}).catch(e=>console.log('GOTO:',e.message.slice(0,80)));
await new Promise(r=>setTimeout(r,2500));
console.log(await p.evaluate(()=>({ title: document.title, bodyLen: document.body.innerHTML.length, hasLogin: !!document.querySelector('#login-form'), ids: [...document.querySelectorAll('[id]')].slice(0,12).map(e=>e.id), scripts: [...document.scripts].map(s=>s.src.split('/').pop()).slice(0,20) })));
await b.close();
