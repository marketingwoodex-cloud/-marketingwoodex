import pptr from 'puppeteer-core'; import cm from '@sparticuz/chromium';
import fs from 'node:fs'; import path from 'node:path'; import { pathToFileURL } from 'node:url';
const ROOT=path.resolve('node_modules');
const { inflate } = await import(pathToFileURL(path.join(ROOT,'@sparticuz/chromium/build/lambdafs.js')).href);
const libDir=await inflate(path.join(ROOT,'@sparticuz/chromium/bin/al2023.tar.br'));
process.env.LD_LIBRARY_PATH=[path.join(libDir,'lib'),process.env.LD_LIBRARY_PATH||''].filter(Boolean).join(':');
const mode=process.argv[2]||'light';
const b=await pptr.launch({executablePath:await cm.executablePath(),args:cm.args,headless:true,defaultViewport:{width:1440,height:950,deviceScaleFactor:3}});
const p=await b.newPage();
await p.goto('http://127.0.0.1:8080/admin/',{waitUntil:'domcontentloaded'});
await p.waitForSelector('#login-form, #nav',{timeout:25000});
if(await p.$('#l-email')){await p.type('#l-email',process.env.PREVIEW_EMAIL);await p.type('#l-pass',process.env.PREVIEW_PASS);await p.click('#l-btn');}
await p.waitForFunction(()=>!!sessionStorage.getItem('wxaTok'),{timeout:30000});
await p.evaluate(m=>{localStorage.setItem('hs_theme',m);},mode);
await p.goto('http://127.0.0.1:8080/admin/?theme='+mode+'&t='+Date.now()+'#/leads',{waitUntil:'domcontentloaded'});
await p.waitForSelector('#nav',{timeout:25000}); await new Promise(r=>setTimeout(r,2500));
fs.mkdirSync('/tmp/side',{recursive:true});
const on = await p.$('.side .nav-a.on'); if(on) await on.screenshot({path:`/tmp/side/${mode}-row.png`});
const grp = await p.$('.side .nav-sec'); if(grp) await grp.screenshot({path:`/tmp/side/${mode}-sec.png`});
const foot = await p.$('.side .side-foot')||await p.$('.side .side-user-row'); if(foot) await foot.screenshot({path:`/tmp/side/${mode}-foot.png`});
const st = await p.evaluate(()=>{const a=document.querySelector('.side .nav-a.on');const g=e=>getComputedStyle(e);const cs=g;
 const pin=a.querySelector('.nav-pin'); const bd=a.querySelector('.nav-bdg'); const nw=a.querySelector('.nav-new');
 return {html:a.innerHTML.replace(/\s+/g,' ').slice(0,220), pin:pin?{o:cs(pin).opacity,d:cs(pin).display,w:cs(pin).width}:null, bdg:bd?{hidden:bd.hidden,d:getComputedStyle(bd).display,t:bd.textContent}:null, nw:nw?getComputedStyle(nw).display:null};});
console.log(mode, JSON.stringify(st,null,1));
await b.close();
